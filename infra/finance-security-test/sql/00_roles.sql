-- Future isolated instance ONLY; executed in one installer transaction.
DO $$ BEGIN
 IF current_database() <> 'finance_security_test' THEN RAISE EXCEPTION 'Wrong DB'; END IF;
 IF (SELECT system_identifier::text FROM pg_control_system()) = '7695793866029359141'
 THEN RAISE EXCEPTION 'Shared cluster forbidden'; END IF;
END $$;
CREATE ROLE fs_owner NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE fs_installer LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE fs_runtime NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE fs_runtime_login LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE fs_authority LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE fs_operator LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
GRANT fs_owner TO fs_installer;
-- Direct command grants to LOGIN; no runtime owner/installer membership.
REVOKE ALL ON DATABASE finance_security_test FROM PUBLIC;
GRANT CONNECT ON DATABASE finance_security_test TO fs_installer,fs_runtime_login,fs_authority,fs_operator;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
CREATE SCHEMA fs_private AUTHORIZATION fs_owner;
CREATE SCHEMA fs_api AUTHORIZATION fs_owner;
REVOKE ALL ON SCHEMA fs_private,fs_api FROM PUBLIC;
GRANT USAGE ON SCHEMA fs_api TO fs_runtime_login,fs_authority,fs_operator;
ALTER DEFAULT PRIVILEGES FOR ROLE fs_owner REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
GRANT EXECUTE ON FUNCTION pg_catalog.pg_control_system() TO fs_owner;
